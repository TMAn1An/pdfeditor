import { describe, expect, it } from 'vitest';
import { PdfTextIndex } from '../src/lib/pdfium/textIndex';
import { generateFilledPdf } from '../src/lib/render/generate';
import { planRow } from '../src/lib/render/plan';
import { FontLibrary } from '../src/lib/fonts/engine';
import { STANDARD_FONTS } from '../src/lib/fonts/standard';
import { projectFor } from './helpers/fixtures';
import { fixture, pageTexts, pdfium } from './helpers/pdfium';
import { textPositions } from './helpers/pdfjsNode';
import type { FontRef, TextField } from '../src/types/project';

/**
 * Regression coverage for a real production incident: an administrator
 * reported that Replace Text worked on the bundled sample PDF but failed
 * on a real certificate they uploaded (a PDF exported from Canva). The
 * actual reported file is NOT committed here -- it named a real individual
 * and included real signature images, so an earlier version of this test
 * used that exact file and has since been scrubbed from this branch's
 * history (see the PR for detail). This fixture,
 * fixtures/pdfs/form-xobject-certificate.pdf (generated by
 * scripts/gen-form-xobject-fixture.mjs, no real names), instead reproduces
 * the exact structural condition confirmed to be the root cause.
 *
 * Root cause, confirmed by direct investigation against the real file
 * before it was removed: the entire page's visible content (text,
 * graphics, images -- everything) was drawn through exactly one top-level
 * Form XObject. PdfTextIndex.page() (textIndex.ts) only collects
 * FPDF_PAGEOBJ_TEXT objects that are direct children of the page; when it
 * instead finds a Form XObject containing text, it does not recurse into
 * it to expose the individual text runs inside -- it reports the whole
 * form as a single opaque "blocked" region (reusing the general, correct
 * caution that a Form XObject may be reused elsewhere, so editing inside
 * it blindly is unsafe). For a page built this way, `objects` is empty and
 * `blocked` has exactly one entry covering virtually the entire page:
 * there is nothing for the "Replace text" tool to select, so native
 * in-place replacement is categorically unavailable, by design, not as a
 * bug to patch.
 *
 * (A lower-level probe reading objects directly via
 * FPDFFormObj_CountObjects/FPDFFormObj_GetObject, bypassing PdfTextIndex,
 * found ~940 real nested text objects inside the real file's one form,
 * confirming the content itself was perfectly normal PDFium-readable text
 * -- just never surfaced through this app's current, deliberately
 * conservative object-collection logic. This fixture only needs two text
 * runs to exercise the same code path.)
 *
 * The correct, already-built answer for a PDF built this way is the
 * "Cover-up patch" tool (TextRunDialog.tsx), driven by PDF.js's text
 * layer instead of PDFium's object graph -- PDF.js finds this text
 * correctly regardless of the Form XObject nesting. This test proves both
 * halves: native replacement is unavailable for a page like this, and the
 * Cover-up-patch fallback actually works end to end against it.
 */
describe('Form-XObject-wrapped certificate (reproduces the real Canva-PDF incident)', () => {
  it('confirms the "Replace text" tool has no selectable objects on this page (everything is inside one Form XObject)', async () => {
    const P = await pdfium();
    const bytes = fixture('form-xobject-certificate.pdf');
    const index = new PdfTextIndex(P, bytes);
    const pg = index.page(1);
    expect(pg.objects).toEqual([]);
    expect(pg.blocked.length).toBe(1);
    expect(pg.blocked[0]!.reason).toMatch(/Form XObject/);
    index.close();
  });

  it('confirms PDF.js *can* extract "JANE DOE" and "Test Role" as real text (not OCR)', async () => {
    const bytes = fixture('form-xobject-certificate.pdf');
    const items = await textPositions(bytes, 1);
    const joined = items.map((i) => i.str).join(' ');
    expect(joined).toContain('JANE DOE');
    expect(joined).toContain('Test Role');
  });

  it('the Cover-up patch fallback (a TextField with a background fill) correctly covers and replaces both strings end to end', async () => {
    const P = await pdfium();
    const bytes = fixture('form-xobject-certificate.pdf');

    // Mirrors exactly what TextRunDialog.tsx's buildField()/addReplacement() produce
    // for a PDF.js-extracted run: a TextField positioned over the run's rect, with a
    // background fill covering the original text, flagged with `replacement` so the
    // UI never confuses it with a plain decorative field or true native replacement.
    const project = projectFor([{ rotation: 0, width: 842.25, height: 595.5 }]);
    const nameField: TextField = {
      id: 'fld_name',
      type: 'text',
      label: 'Replace "JANE DOE"',
      page: 1,
      rect: { x: 0.3, y: 0.48, w: 0.25, h: 0.08 },
      required: false,
      sampleValue: 'TEST PARTICIPANT',
      replacement: { originalText: 'JANE DOE' },
      style: {
        font: 'std:Helvetica' as FontRef,
        fallbackFont: null,
        fontSize: 32,
        minFontSize: 6,
        lineHeight: 1.2,
        color: '#000000',
        align: 'left',
        verticalAlign: 'middle',
        padding: 0.5,
        fit: 'shrink',
        rotation: 0,
        background: '#ffffff',
      },
    };
    const roleField: TextField = {
      ...nameField,
      id: 'fld_role',
      label: 'Replace "Test Role"',
      rect: { x: 0.69, y: 0.56, w: 0.1, h: 0.03 },
      sampleValue: 'Session Chair',
      replacement: { originalText: 'Test Role' },
      style: { ...nameField.style, fontSize: 14 },
    };
    project.fields = [nameField, roleField];
    project.mapping = {
      fld_name: { kind: 'fixed', value: 'TEST PARTICIPANT' },
      fld_role: { kind: 'fixed', value: 'Session Chair' },
    };

    const fonts = new FontLibrary(() => undefined);
    await fonts.prepare(STANDARD_FONTS.map((f) => `std:${f.id}` as FontRef));
    const plan = planRow({ project, fonts, textIndex: null, images: { index: null, assets: new Map(), overrides: {}, samples: {} } }, null, null);
    expect(plan.texts.length).toBe(2);

    const { bytes: outBytes } = await generateFilledPdf({
      templateBytes: bytes,
      plan,
      formMode: 'flatten',
      formFieldFont: 'std:Helvetica',
      fontBytes: () => undefined,
    });

    // Independent verification via PDF.js re-extraction of the exported output.
    const outItems = await textPositions(outBytes, 1);
    const outJoined = outItems.map((i) => i.str).join(' ');
    expect(outJoined).toContain('TEST PARTICIPANT');
    expect(outJoined).toContain('Session Chair');
    // By design, the cover-up patch does not remove the original text from the PDF's
    // text structure -- only paints over it visually -- so it must still be present.
    expect(outJoined).toContain('JANE DOE');
    expect(outJoined).toContain('Test Role');

    // Independent verification via PDFium's own text extraction too.
    const pdfiumTexts = pageTexts(P, outBytes).map((t) => t.text).join(' ');
    expect(pdfiumTexts).toContain('TEST PARTICIPANT');
    expect(pdfiumTexts).toContain('Session Chair');
  });
});
